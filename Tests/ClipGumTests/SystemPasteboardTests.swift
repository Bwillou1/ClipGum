import AppKit
import XCTest
@testable import ClipGum

@MainActor
final class SystemPasteboardTests: XCTestCase {
    private var pasteboard: NSPasteboard!
    private var systemPasteboard: SystemPasteboard!

    override func setUp() {
        super.setUp()
        let name = NSPasteboard.Name("ClipGumTests.\(UUID().uuidString)")
        pasteboard = NSPasteboard(name: name)
        systemPasteboard = SystemPasteboard(pasteboard: pasteboard)
        pasteboard.clearContents()
    }

    override func tearDown() {
        pasteboard.clearContents()
        systemPasteboard = nil
        pasteboard = nil
        super.tearDown()
    }

    func testReadsOnePlainTextItemExactly() {
        let input = "  Hello 👋\nline two  "
        writeItems([makeItem(text: input)])

        XCTAssertEqual(systemPasteboard.readTextForExplicitUserAction(), .text(input))
    }

    func testUniversalSensitiveMarkersAreRejectedBeforeTextIsReturned() {
        for marker in [
            PasteboardTypePolicy.concealed,
            PasteboardTypePolicy.transient,
            PasteboardTypePolicy.autoGenerated
        ] {
            pasteboard.clearContents()
            let item = makeItem(text: "never return this")
            XCTAssertTrue(item.setString("", forType: NSPasteboard.PasteboardType(marker)))
            writeItems([item])

            XCTAssertEqual(
                systemPasteboard.readTextForExplicitUserAction(),
                .excluded(marker: marker)
            )
        }
    }

    func testSensitiveMarkerOnAnyItemRejectsTheWholeRead() {
        let visible = makeItem(text: "visible")
        let sensitive = makeItem(text: "sensitive")
        XCTAssertTrue(sensitive.setString(
            "",
            forType: NSPasteboard.PasteboardType(PasteboardTypePolicy.concealed)
        ))
        writeItems([visible, sensitive])

        XCTAssertEqual(
            systemPasteboard.readTextForExplicitUserAction(),
            .excluded(marker: PasteboardTypePolicy.concealed)
        )
    }

    func testLegacyPasswordManagerMarkerIsRejected() {
        let item = makeItem(text: "never return this")
        let marker = "com.agilebits.onepassword"
        XCTAssertTrue(item.setString("", forType: NSPasteboard.PasteboardType(marker)))
        writeItems([item])

        XCTAssertEqual(
            systemPasteboard.readTextForExplicitUserAction(),
            .excluded(marker: marker)
        )
    }

    func testMultipleOrdinaryItemsAreRejectedWithoutCombiningThem() {
        writeItems([makeItem(text: "one"), makeItem(text: "two")])

        XCTAssertEqual(systemPasteboard.readTextForExplicitUserAction(), .multipleItems)
    }

    func testNonTextAndEmptyItemsHaveDistinctResults() {
        let nonText = NSPasteboardItem()
        XCTAssertTrue(nonText.setData(Data([0x01]), forType: .png))
        writeItems([nonText])
        XCTAssertEqual(systemPasteboard.readTextForExplicitUserAction(), .noText)

        writeItems([makeItem(text: "")])
        XCTAssertEqual(systemPasteboard.readTextForExplicitUserAction(), .emptyText)
    }

    func testReadNeverMutatesPasteboard() {
        writeItems([makeItem(text: "unchanged")])
        let changeCount = pasteboard.changeCount

        _ = systemPasteboard.readTextForExplicitUserAction()

        XCTAssertEqual(pasteboard.changeCount, changeCount)
        XCTAssertEqual(pasteboard.string(forType: .string), "unchanged")
    }

    func testExplicitWriteIsTheOnlyOperationThatChangesContents() {
        writeItems([makeItem(text: "before")])
        let changeCount = pasteboard.changeCount

        XCTAssertNoThrow(try systemPasteboard.writeTextForExplicitUserAction("after"))

        XCTAssertGreaterThan(pasteboard.changeCount, changeCount)
        XCTAssertEqual(pasteboard.string(forType: .string), "after")
    }

    private func makeItem(text: String) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        XCTAssertTrue(item.setString(text, forType: .string))
        return item
    }

    private func writeItems(_ items: [NSPasteboardItem]) {
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.writeObjects(items))
    }
}
