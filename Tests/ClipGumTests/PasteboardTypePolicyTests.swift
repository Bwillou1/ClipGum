import XCTest
@testable import ClipGum

final class PasteboardTypePolicyTests: XCTestCase {
    func testAllUniversalSensitiveMarkersAreRejected() {
        for marker in [
            PasteboardTypePolicy.concealed,
            PasteboardTypePolicy.transient,
            PasteboardTypePolicy.autoGenerated
        ] {
            XCTAssertEqual(
                PasteboardTypePolicy.firstIgnoredMarker(in: ["public.utf8-plain-text", marker]),
                marker
            )
        }
    }

    func testLegacyPasswordManagerAndTransientMarkersAreRejected() {
        for marker in [
            "com.agilebits.onepassword",
            "com.typeit4me.clipping",
            "de.petermaurer.TransientPasteboardType",
            "Pasteboard generator type",
            "net.antelle.keeweb"
        ] {
            XCTAssertEqual(PasteboardTypePolicy.firstIgnoredMarker(in: [marker]), marker)
        }
    }

    func testOrdinaryContentTypesAreAcceptedByMetadataPolicy() {
        XCTAssertNil(PasteboardTypePolicy.firstIgnoredMarker(in: [
            "public.utf8-plain-text", "public.html", "org.nspasteboard.source"
        ]))
    }

    func testMarkerSelectionIsDeterministic() {
        let types: Set<String> = [PasteboardTypePolicy.transient, PasteboardTypePolicy.concealed]
        let first = PasteboardTypePolicy.firstIgnoredMarker(in: types)
        let second = PasteboardTypePolicy.firstIgnoredMarker(in: Set(types.reversed()))
        XCTAssertEqual(first, second)
    }

    func testUserInitiatedAccessPolicyAllowsLegacyDefaultAskAndAlwaysAllow() {
        let values: [Int?] = [nil, 0, 1, 2]
        for value in values {
            XCTAssertTrue(PasteboardAccessPolicy.allowsUserInitiatedRead(rawValue: value))
        }
    }

    func testUserInitiatedAccessPolicyFailsClosedForDenyAndUnknownValues() {
        for value in [-1, 3, 4, 99] {
            XCTAssertFalse(PasteboardAccessPolicy.allowsUserInitiatedRead(rawValue: value))
        }
    }
}
