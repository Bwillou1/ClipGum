import Foundation

/// Metadata-only policy evaluated before any pasteboard value is read.
enum PasteboardTypePolicy {
    static let concealed = "org.nspasteboard.ConcealedType"
    static let transient = "org.nspasteboard.TransientType"
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    /// Universal markers plus legacy password-manager/transient conventions
    /// also ignored by Maccy. These are never configurable in Phase 1.
    static let ignoredTypes: Set<String> = [
        concealed,
        transient,
        autoGenerated,
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ]

    static func firstIgnoredMarker(in types: Set<String>) -> String? {
        ignoredTypes.intersection(types).sorted().first
    }
}

/// Raw values documented by NSPasteboard.AccessBehavior (macOS 15.4+).
/// Keeping the decision here makes the fail-closed behavior testable on macOS 14.
enum PasteboardAccessPolicy {
    static func allowsUserInitiatedRead(rawValue: Int?) -> Bool {
        // macOS 14 does not expose accessBehavior. The caller is still required
        // to be handling an explicit user trigger; no background reads exist.
        guard let rawValue else {
            return true
        }

        switch rawValue {
        case 0, 1, 2: // .default, .ask, .alwaysAllow
            // The explicit action may produce Apple's pasteboard consent alert.
            return true
        case 3: // .alwaysDeny
            return false
        default:
            // Unknown future values fail closed.
            return false
        }
    }
}
