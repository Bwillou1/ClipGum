import AppKit
import ClipGumCore
import Foundation

/// Native NSServices provider. The service pasteboard is supplied by the
/// invoking application; this type never reads NSPasteboard.general.
@MainActor
final class QuickActionServicesProvider: NSObject {
    private let sensitiveMarkers: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    @objc(cleanAndPasteWithClipGum:userData:error:)
    func cleanAndPasteWithClipGum(
        _ pasteboard: NSPasteboard,
        userData: String,
        error errorPointer: NSErrorPointer
    ) {
        guard pasteboard.types?.contains(where: { sensitiveMarkers.contains($0) }) != true else {
            setError(errorPointer, message: "ClipGum skipped a sensitive service selection.")
            return
        }
        guard let input = pasteboard.string(forType: .string), !input.isEmpty else {
            setError(errorPointer, message: "Select text before invoking ClipGum.")
            return
        }
        let result = DeterministicTransforms.sanitize(input)
        pasteboard.clearContents()
        guard pasteboard.setString(result.output, forType: .string) else {
            setError(errorPointer, message: "ClipGum could not return the sanitized selection.")
            return
        }
    }

    private func setError(_ pointer: NSErrorPointer, message: String) {
        pointer?.pointee = NSError(
            domain: "com.clipgum.ClipGum.Services",
            code: 1,
            userInfo: [NSLocalizedDescriptionKey: message]
        )
    }
}
